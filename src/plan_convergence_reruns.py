"""Plan the Sobol reruns that a convergence criterion still asks for.

Reads convergence/convergence_stats.csv - the table sobol_convergence.xlsx is
built from - and takes every combination at the largest N it has been run at.
Those that fail the chosen criterion (default: ranking on ST, the 95th
percentile of the weighted rank distance below 1, Sarrazin et al. 2016 Eq. 3)
are rerun at max(--min-n, 2 x their current N). A combination that already
failed at 32768 therefore goes to 65536, never to the same N again.

Writes a dated folder convergence/reruns/<YYYYmmdd_HHMM>/, nothing if every
combination passes:
  plan.csv              the combinations, their statistic, current and new N
  <scenario>_n<N>.txt   one "COUNTRY ASSET" per line
  snapshot_n<N>.csv     the combinations whose derived files are backed up
  submit.sh             records every existing archive of these combinations,
                        backs up their derived files (src.snapshot_results),
                        submits one Sobol-only rerun (run_study --force-sobol:
                        LHS untouched) per (scenario, N) list through
                        submit_miraca_uncertainty_study.sh addscen, then a job
                        that waits for all of them, checks the old archives are
                        intact, tests the new ones (convergence_tests --resume),
                        rebuilds both workbooks and runs this planner again for
                        whatever is left
  check_archives.sh     the archive check, also runnable by hand

    python -m src.plan_convergence_reruns                       # ST ranking (rho)
    python -m src.plan_convergence_reruns --index ST --criterion value
and then, on the cluster:
    DRY=1 bash convergence/reruns/<stamp>/submit.sh             # preview
    bash convergence/reruns/<stamp>/submit.sh                   # submit
"""
from __future__ import annotations

import argparse
from datetime import datetime
from pathlib import Path

import pandas as pd

from .convergence_tests import CRITERIA, INDICES, OUT_DIR, highest_n
from .paths import load_config
from .sobol_design import runs_per_base, second_order_enabled

CRIT = {c[0]: c for c in CRITERIA}

SUBMIT_HEAD = """\
#!/bin/bash
# Generated by python -m src.plan_convergence_reruns on {when}.
# Criterion: {index} {crit} ({title}, converged if {conv_if}) at each
# combination's highest N. {n_combos} combination(s) -> {n_lists} rerun list(s);
# see plan.csv.
#
# Nothing from before is lost:
#   1. every existing archive of these combinations is listed with its size in
#      archives_before.txt; the retest job checks them all first (check_archives.sh)
#   2. the derived files a rerun rewrites in place (_sobol_indices.csv and its
#      figure) are copied to {snapshot_dirs} by src.snapshot_results, which never
#      overwrites an existing snapshot; if it fails, nothing is submitted
#   3. the reruns are Sobol-only (--force-sobol): the LHS archive,
#      _feature_scores.csv and the LHS figures are not touched, and the new
#      Sobol archive lands beside the old one as ..._sobol_n<N>_<timestamp>.tar.gz
#
#   DRY=1 bash {rel}/submit.sh     # print what would be done
#   bash {rel}/submit.sh           # back up, then submit
#
# Walltime, partition and node exclusion can be overridden from the
# environment (SCEN_TIME, SCEN_TIME_LIGHT, PARTITION, EXCLUDE).
set -euo pipefail
HERE=$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)
REPO=$(cd "${{HERE}}/../../.." && pwd)
SUBMIT="${{REPO}}/submit_miraca_uncertainty_study.sh"
PYTHON=${{PYTHON:-/scistor/ivm/${{USER:-$(id -un)}}/.venvs/miraca_uq/bin/python}}
MODULES=${{MODULES:-"gdal/3.6.2"}}
export MIRACA_CONFIG=${{MIRACA_CONFIG:-${{REPO}}/config.cluster.yml}}
export PYTHON MODULES
export EXCLUDE=${{EXCLUDE:-node009}}
export SCEN_TIME=${{SCEN_TIME:-120:00:00}}
export SCEN_TIME_LIGHT=${{SCEN_TIME_LIGHT:-120:00:00}}
export FORCE_SOBOL=1
JOBS=()

# -- 1. inventory of the archives that must survive ----------------------------
if [[ -z "${{DRY:-}}" ]]; then
    if [[ -f "${{HERE}}/archives_before.txt" ]]; then
        echo "archives_before.txt exists - this plan was submitted before; not resubmitting." >&2
        echo "Make a new plan with: python -m src.plan_convergence_reruns" >&2
        exit 1
    fi
    {{
{manifest}
    }} > "${{HERE}}/archives_before.txt"
    echo "Recorded $(wc -l < "${{HERE}}/archives_before.txt") existing archive(s) in archives_before.txt"
fi

# -- 2. back up the derived files a rerun rewrites in place --------------------
cd "${{REPO}}"
{snapshots}

# -- 3. the reruns --------------------------------------------------------------
"""

CHECK_ARCHIVES = """\
#!/bin/bash
# Every archive recorded in archives_before.txt (size, path) must still exist
# with the same size. Run by the retest job before anything else; safe to run
# by hand at any time.
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
lost=0
while read -r size path; do
    if [[ ! -f "$path" ]] || [[ "$(stat -c %s "$path")" != "$size" ]]; then
        echo "!! missing or changed: $path" >&2
        lost=$((lost + 1))
    fi
done < "${HERE}/archives_before.txt"
total=$(wc -l < "${HERE}/archives_before.txt")
if [[ $lost -gt 0 ]]; then
    echo "!! ${lost} of ${total} archives from before the reruns are missing or changed." >&2
    exit 1
fi
echo "All ${total} archives from before the reruns are intact."
"""

_RERUN_FN = """\
rerun() {{   # scenario N list-file
    local scen="$1" n="$2" list="${{HERE}}/$3" out
    if [[ -n "${{DRY:-}}" ]]; then
        echo "${{scen}} at N=${{n}}: $(grep -v '^#' "$list" | tr '\\n' ' ')"
        return
    fi
    out=$(SCEN="$scen" SOBOL_N="$n" ADDSCEN_LIST="$list" SCEN_TAG="conv_${{scen}}_n${{n}}" \\
          "$SUBMIT" addscen)
    echo "$out"
    JOBS+=($(grep -o 'run=[0-9]*' <<<"$out" | cut -d= -f2 || true))
}}

"""

SUBMIT_TAIL = """
[[ -n "${{DRY:-}}" ]] && exit 0
if [[ ${{#JOBS[@]}} -eq 0 ]]; then
    echo "No rerun job ids captured - not chaining the retest." >&2
    exit 1
fi

# Retest once every rerun has ended; afterany, so one failed rerun cannot hold
# back the rest. The planner at the end writes the next round, if one is needed.
dep=$(IFS=:; echo "${{JOBS[*]}}")
retest=$(sbatch --parsable --dependency=afterany:${{dep}} <<SLURM
#!/bin/bash -l
#SBATCH --job-name=conv_retest
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=32
#SBATCH --mem=64G
#SBATCH --time=120:00:00
${{PARTITION:+#SBATCH --partition=${{PARTITION}}}}
#SBATCH --exclude=${{EXCLUDE}}
#SBATCH --output=${{HERE}}/retest_%j.out
#SBATCH --error=${{HERE}}/retest_%j.err
set -euo pipefail
export MIRACA_CONFIG=${{REPO}}/config.cluster.yml
module load ${{MODULES}}
cd ${{REPO}}
bash ${{HERE}}/check_archives.sh
${{PYTHON}} -W ignore -m src.convergence_tests --resume --workers 32
${{PYTHON}} -m src.screening_factors
${{PYTHON}} -m src.plan_convergence_reruns {replan}
SLURM
)
echo
echo "Submitted ${{#JOBS[@]}} rerun job(s); retest job ${{retest}} runs after them."
echo "Results: ${{REPO}}/convergence/sobol_convergence.xlsx; log: ${{HERE}}/retest_${{retest}}.out"
"""


def plan(stats: pd.DataFrame, index: str, crit: str, min_n: int) -> tuple[pd.DataFrame, pd.DataFrame]:
    """(combinations to rerun, combinations whose highest-N run errored)."""
    conv_col, stat_col = CRIT[crit][5], CRIT[crit][4]
    top = highest_n(stats)
    top = top[top["index"] == index]
    errored = top[top["status"] == "error"]
    ok = top[top["status"] == "ok"]
    todo = ok[~ok[conv_col].fillna(False).astype(bool)].copy()
    todo["statistic"] = todo[stat_col]
    todo["current_n"] = todo["n"].astype(int)
    todo["new_n"] = todo["current_n"].map(lambda n: max(min_n, 2 * n))
    k = todo["n_factors"].astype(int)
    # The reruns sample with whatever the config says now (sobol.second_order).
    todo["model_runs"] = todo["new_n"] * runs_per_base(k, second_order_enabled(load_config()))
    cols = ["country", "asset", "scenario", "n_factors", "current_n", "statistic",
            "top_factor", "new_n", "model_runs"]
    return (todo[cols].sort_values(["scenario", "new_n", "country", "asset"])
            .reset_index(drop=True), errored)


def write_plan(todo: pd.DataFrame, out_root: Path, args, when: datetime) -> Path:
    folder = out_root / when.strftime("%Y%m%d_%H%M")
    folder.mkdir(parents=True, exist_ok=False)
    todo.to_csv(folder / "plan.csv", index=False)
    calls = []
    for (scen, n), grp in todo.groupby(["scenario", "new_n"], sort=True):
        name = f"{scen}_n{n}.txt"
        with open(folder / name, "w", newline="\n") as fh:
            was = ", ".join(str(int(x)) for x in sorted(set(grp["current_n"])))
            fh.write(f"# {args.index} {args.criterion} not converged at N = {was}"
                     f" -> rerun {scen} at N = {n}\n")
            for c, a in zip(grp["country"], grp["asset"]):
                fh.write(f"{c} {a}\n")
        calls.append(f"rerun {scen} {n} {name}")
    # Archives of every listed combination - LHS and Sobol, any N.
    manifest = "\n".join(
        f'        find "${{REPO}}/results/{c}" -maxdepth 1 -name "experiments_{c}_{a}_{s}_*.tar.gz" '
        "-printf '%s %p\\n'"
        for c, a, s in todo[["country", "asset", "scenario"]].drop_duplicates().itertuples(index=False))
    # One snapshot per current N, tagged so it can never collide with an older one.
    snapshots, snapshot_dirs = [], []
    for n, grp in todo.groupby("current_n"):
        tag = f"n{n}_pre_rerun_{when.strftime('%Y%m%d_%H%M')}"
        grp[["country", "asset", "scenario"]].to_csv(folder / f"snapshot_n{n}.csv", index=False)
        snapshots.append(f'"${{PYTHON}}" -m src.snapshot_results --list "${{HERE}}/snapshot_n{n}.csv" '
                         f'--tag {tag} ${{DRY:+--dry-run}}')
        snapshot_dirs.append(f"results_snapshot_{tag}/")
    _, title, _, conv_if, *_ = CRIT[args.criterion]
    rel = folder.relative_to(out_root.parent.parent).as_posix()
    replan = f"--index {args.index} --criterion {args.criterion} --min-n {args.min_n}"
    script = (SUBMIT_HEAD.format(when=when.strftime("%Y-%m-%d %H:%M"), index=args.index,
                                 crit=args.criterion, title=title, conv_if=conv_if,
                                 n_combos=len(todo), n_lists=len(calls), rel=rel,
                                 snapshot_dirs=", ".join(snapshot_dirs), manifest=manifest,
                                 snapshots="\n".join(snapshots))
              + _RERUN_FN.format() + "\n".join(calls) + "\n"
              + SUBMIT_TAIL.format(replan=replan))
    with open(folder / "submit.sh", "w", newline="\n") as fh:
        fh.write(script)
    with open(folder / "check_archives.sh", "w", newline="\n") as fh:
        fh.write(CHECK_ARCHIVES)
    return folder


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--index", choices=INDICES, default="ST")
    ap.add_argument("--criterion", choices=list(CRIT), default="rank-rho")
    ap.add_argument("--min-n", type=int, default=32768,
                    help="smallest N to rerun at; never less than twice the current N")
    ap.add_argument("--out-dir", default=None,
                    help=f"folder with convergence_stats.csv (default {OUT_DIR})")
    args = ap.parse_args()

    out_dir = Path(args.out_dir) if args.out_dir else OUT_DIR
    stats = pd.read_csv(out_dir / "convergence_stats.csv")
    todo, errored = plan(stats, args.index, args.criterion, args.min_n)
    if len(errored):
        print(f"!! {len(errored)} combination(s) errored at their highest N and cannot be "
              "judged - rerun python -m src.convergence_tests --resume first:")
        print(errored[["country", "asset", "scenario", "n", "error"]].to_string(index=False))
    if todo.empty:
        print(f"All tested combinations pass {args.index} {args.criterion} at their highest N; "
              "nothing to rerun.")
        return
    folder = write_plan(todo, out_dir / "reruns", args, datetime.now())
    print(todo.to_string(index=False))
    print(f"\n{len(todo)} combination(s) to rerun, {todo['model_runs'].sum():,} model runs in all.")
    print(f"Wrote {folder}. On the cluster:  DRY=1 bash {folder.relative_to(out_dir.parent).as_posix()}"
          "/submit.sh")


if __name__ == "__main__":
    main()
